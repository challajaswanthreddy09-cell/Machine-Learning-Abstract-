"""## 2. Arithmetic & Comparison Operators
Arithmetic operators do math. Comparison operators ask a true/false question - this is how you will filter rows of a dataset (e.g. "is this student's CGPA above 8?").
"""

# --- ARITHMETIC OPERATORS ---
a = 7
b = 2
print("a + b =", a + b)     # addition
print("a - b =", a - b)     # subtraction
print("a * b =", a * b)     # multiplication
print("a / b =", a / b)     # division (always gives a float)
